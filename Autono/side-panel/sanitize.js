/**
 * Autono: strict allowlist HTML sanitiser for model / page-derived content shown in extension pages.
 *
 * Why it exists: model output (which can be steered by any web page the agent read) is rendered in the
 * privileged side panel. Raw HTML there can load remote images (data exfiltration), inject <style>/<form>/
 * <input data-mirror> (UI overlay, key theft) etc. Everything goes through sanitizeHtml() first.
 *
 * Design: parse with the browser's own parser (DOMParser, inert document: no script runs, no resource loads),
 * then rebuild: only allowlisted tags, only allowlisted attributes, only safe URL schemes. Anything unknown
 * is unwrapped (its text kept) or removed with its content (dangerous containers). It is a pure function of the
 * input string and uses only a tiny DOM surface, so it can be unit-tested with a stub parser (tests/).
 *
 * Trusted markup generated by the extension itself (KaTeX output, copy buttons, cards...) must be added AFTER
 * sanitising, or through DOM APIs, never passed through here.
 */

const HTML_NS = 'http://www.w3.org/1999/xhtml';

// Elements kept (everything else is unwrapped or dropped)
const ALLOWED_TAGS = new Set([
  'p', 'br', 'hr', 'strong', 'em', 'b', 'i', 'u', 's', 'del', 'ins', 'code', 'pre', 'blockquote', 'kbd', 'mark',
  'ul', 'ol', 'li', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6',
  'table', 'thead', 'tbody', 'tfoot', 'tr', 'th', 'td', 'caption',
  'a', 'img', 'span', 'div', 'sup', 'sub', 'details', 'summary',
]);

// Removed together with everything inside them
const DROP_WITH_CONTENT = new Set([
  'script', 'style', 'iframe', 'frame', 'frameset', 'object', 'embed', 'applet', 'meta', 'base', 'link', 'svg', 'math',
  'template', 'noscript', 'noembed', 'noframes', 'title', 'head', 'select', 'textarea', 'option', 'optgroup',
  'input', 'button', 'canvas', 'audio', 'video', 'source', 'track', 'portal', 'dialog', 'slot', 'xmp', 'plaintext',
]);

const MAX_URL_LENGTH = 8192;

function stripControl(s) {
  // The URL parser ignores tabs/newlines/leading control characters: so must the scheme check
  let out = '';
  for (const ch of String(s)) {
    const c = ch.codePointAt(0);
    if (c <= 0x20 || (c >= 0x7f && c <= 0x9f) || c === 0xad || (c >= 0x200b && c <= 0x200f) || c === 0x2028 || c === 0x2029 || c === 0xfeff) continue;
    out += ch;
  }
  return out;
}

/** http(s) and mailto only. Returns the cleaned URL or '' */
export function safeLinkUrl(raw) {
  if (typeof raw !== 'string' || raw.length > MAX_URL_LENGTH) return '';
  const compact = stripControl(raw);
  if (!/^(https?:\/\/|mailto:)/i.test(compact)) return '';
  try {
    const u = new URL(compact);
    if (u.protocol !== 'http:' && u.protocol !== 'https:' && u.protocol !== 'mailto:') return '';
    if ((u.protocol === 'http:' || u.protocol === 'https:') && (u.username || u.password)) return '';
    return u.href;
  } catch (_) {
    return '';
  }
}

/** Image sources that need no network: raster data URIs, blob: and the extension's own files. Returns '' otherwise */
export function safeImageUrl(raw, extensionBase = '') {
  if (typeof raw !== 'string' || raw.length > 2 * 1024 * 1024) return '';
  const compact = stripControl(raw);
  if (/^data:image\/(png|jpe?g|gif|webp);base64,[a-z0-9+/=]+$/i.test(compact)) return compact;
  if (/^blob:/i.test(compact)) return compact;
  if (extensionBase && compact.startsWith(extensionBase)) return compact;
  return '';
}

function getDoc(html) {
  const doc = new DOMParser().parseFromString(String(html == null ? '' : html), 'text/html');
  return doc;
}

function isHtmlElement(el) {
  // svg / math (foreign content) are never kept, whatever their tag name says
  return !el.namespaceURI || el.namespaceURI === HTML_NS;
}

function attrNames(el) {
  const out = [];
  const attrs = el.attributes;
  for (let i = 0; i < attrs.length; i++) out.push(attrs[i].name);
  return out;
}

function cleanAttributes(el, tag, ctx) {
  const keep = {};
  const get = (n) => el.getAttribute(n);
  if (tag === 'a') {
    const href = get('href');
    if (href != null) keep.href = href;
    const title = get('title');
    if (title != null) keep.title = title;
  } else if (tag === 'img') {
    for (const n of ['src', 'alt', 'title']) {
      const v = get(n);
      if (v != null) keep[n] = v;
    }
  } else if (tag === 'th' || tag === 'td') {
    const align = (get('align') || '').toLowerCase();
    if (align === 'left' || align === 'right' || align === 'center') keep.align = align;
  } else if (tag === 'ol') {
    const start = get('start');
    if (start != null && /^\d{1,6}$/.test(start)) keep.start = start;
  } else if (tag === 'code') {
    const cls = get('class');
    if (cls != null && /^language-[\w+#.-]{1,40}$/.test(cls)) keep.class = cls;
  } else if (tag === 'details') {
    if (el.hasAttribute('open')) keep.open = '';
  }
  // Drop everything (on*, style, id, name, data-*, srcset, class, ...), then put back only what is allowed
  for (const n of attrNames(el)) el.removeAttribute(n);
  for (const [n, v] of Object.entries(keep)) {
    if (typeof v !== 'string') continue;
    // Placeholder tokens (%%%...%%%) are replaced by trusted HTML later: never allow them inside attributes
    if (v.includes('%%%')) continue;
    el.setAttribute(n, v.slice(0, MAX_URL_LENGTH));
  }
  if (tag === 'a') {
    const safe = safeLinkUrl(el.getAttribute('href') || '');
    if (!safe) return false; // unwrap: keep the text, no link
    el.setAttribute('href', safe);
    el.setAttribute('target', '_blank');
    el.setAttribute('rel', 'noopener noreferrer');
  } else if (tag === 'img') {
    const src = el.getAttribute('src') || '';
    const safe = safeImageUrl(src, ctx.extensionBase);
    if (safe) el.setAttribute('src', safe);
    else return false; // handled by the caller: becomes a plain link / text
  }
  return true;
}

function replaceWithChildren(doc, parent, node) {
  while (node.firstChild) parent.insertBefore(node.firstChild, node);
  parent.removeChild(node);
}

function walk(doc, parent, ctx, depth) {
  if (depth > 60) { // absurd nesting: drop the rest
    while (parent.firstChild) parent.removeChild(parent.firstChild);
    return;
  }
  const kids = Array.prototype.slice.call(parent.childNodes);
  for (const node of kids) {
    if (node.nodeType === 3) continue; // text
    if (node.nodeType !== 1) { parent.removeChild(node); continue; } // comments, PIs, ...
    const tag = String(node.localName || node.nodeName || '').toLowerCase();
    if (!isHtmlElement(node) || DROP_WITH_CONTENT.has(tag)) { parent.removeChild(node); continue; }
    if (!ALLOWED_TAGS.has(tag)) {
      // unknown / structural tags (form, label, section, font...): keep the contents, sanitised
      // (the moved children are cleaned by the next pass of sanitizeToElement)
      replaceWithChildren(doc, parent, node);
      continue;
    }
    const ok = cleanAttributes(node, tag, ctx);
    if (!ok) {
      if (tag === 'img') {
        const raw = node.getAttribute('src') || '';
        const alt = node.getAttribute('alt') || '';
        const link = safeLinkUrl(raw);
        let repl;
        if (link && link.startsWith('http')) {
          repl = doc.createElement('a');
          repl.setAttribute('href', link);
          repl.setAttribute('target', '_blank');
          repl.setAttribute('rel', 'noopener noreferrer');
          repl.appendChild(doc.createTextNode(alt ? `[image: ${alt.slice(0, 80)}]` : '[image]'));
        } else {
          repl = doc.createTextNode(alt ? `[image: ${alt.slice(0, 80)}]` : '[image]');
        }
        parent.replaceChild(repl, node);
      } else {
        replaceWithChildren(doc, parent, node);
        // the unwrapped children still have to be cleaned: handled by the second pass in sanitizeToElement
      }
      continue;
    }
    walk(doc, node, ctx, depth + 1);
  }
}

/**
 * Returns the sanitised <body> element of an inert document (children are safe to serialise or move).
 * Runs the walk until the tree is stable so that unwrapped children are cleaned too.
 */
export function sanitizeToElement(html, options = {}) {
  const doc = getDoc(html);
  const body = doc.body;
  const ctx = { extensionBase: options.extensionBase || '' };
  for (let pass = 0; pass < 8; pass++) {
    walk(doc, body, ctx, 0);
    if (isClean(body, ctx)) return body;
  }
  // Never converged (pathological input): fall back to plain text
  const text = body.textContent || '';
  while (body.firstChild) body.removeChild(body.firstChild);
  body.appendChild(doc.createTextNode(text));
  return body;
}

function isClean(root, ctx) {
  let clean = true;
  (function check(parent) {
    const kids = parent.childNodes;
    for (let i = 0; i < kids.length && clean; i++) {
      const n = kids[i];
      if (n.nodeType === 3) continue;
      if (n.nodeType !== 1) { clean = false; return; }
      const tag = String(n.localName || n.nodeName || '').toLowerCase();
      if (!isHtmlElement(n) || DROP_WITH_CONTENT.has(tag) || !ALLOWED_TAGS.has(tag)) { clean = false; return; }
      const names = attrNames(n);
      const allowedAttrs = {
        a: ['href', 'title', 'target', 'rel'], img: ['src', 'alt', 'title'], th: ['align'], td: ['align'],
        ol: ['start'], code: ['class'], details: ['open'],
      }[tag] || [];
      for (const name of names) {
        if (!allowedAttrs.includes(name)) { clean = false; return; }
      }
      if (tag === 'a' && !safeLinkUrl(n.getAttribute('href') || '')) { clean = false; return; }
      if (tag === 'img' && !safeImageUrl(n.getAttribute('src') || '', ctx.extensionBase)) { clean = false; return; }
      check(n);
    }
  })(root);
  return clean;
}

/** Sanitised markup as a string (same rules). */
export function sanitizeHtml(html, options = {}) {
  return sanitizeToElement(html, options).innerHTML;
}

/** Escapes text for use inside element content or a quoted attribute. */
export function escapeText(str) {
  return String(str == null ? '' : str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
